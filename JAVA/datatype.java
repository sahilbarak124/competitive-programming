package JAVA;
public class datatype {
    public static void main(String args[]) {
        byte b=8;
        System.out.println(b);
        char c='a';
        System.out.println(c);
        boolean var=true;
        System.out.println(var);
        float f=10.5f;
        System.out.println(f);
        double d=10.5;
        System.out.println(d);
        long l=1000000000;
        System.out.println(l);
        short s=1000;
        System.out.println(s);
    }
}                                             
